def render_story_page(story: dict, body_html: str, shell: str,
                      newer: dict | None = None, older: dict | None = None) -> str:
    """Full standalone HTML reading page for one local Field Note, filled into
    the theme's `reading` archetype shell (themes/<slug>/archetypes/reading.html
    — see docs/theme-archetypes.md). Frontmatter drives the header; `body_html`
    is the already-rendered markdown body; `newer`/`older` are the adjacent
    local notes for the prev/next pager (None at the ends).

    Field Note pages are fully regenerated every render (STORY_PAGE_MARKER
    forbids hand-editing them), so unlike index.html's SITE_JSON zones — which
    must survive in the output for the *next* render to find them again — the
    `{{READING:...}}` tokens below are consumed whole and never appear in the
    rendered output."""
    raw_title = str(story.get("title", ""))
    title = esc(raw_title)
    subtitle = str(story.get("subtitle") or story.get("tagline") or "")
    published = esc(str(story.get("published", "")))
    product = esc(str(story.get("product", "")))
    author = esc(str(story.get("author") or "626 Labs"))
    canonical = f"{SITE_URL}/editorial/{story_slug(story)}/"
    desc = subtitle or raw_title

    img = story.get("image") or story.get("og_image") or story.get("hero_image")
    if img:
        og_image = str(img)
        if og_image.startswith("/"):
            og_image = f"{SITE_URL}{og_image}"
    elif (ROOT / "assets" / "og" / f"{story_slug(story)}.png").exists():
        # Auto-generated branded social card (scripts/build-og-cards.py); falls
        # back to the generic brand banner when a story has no card yet.
        og_image = f"{SITE_URL}/assets/og/{story_slug(story)}.png"
    else:
        og_image = f"{SITE_URL}/assets/brand/medium-header-1500x600.png"

    # BlogPosting structured data — completes the JSON-LD coverage the homepage
    # (#29) and plugin pages (#30) already have. Built as a dict + json.dumps so
    # titles with quotes/em-dashes escape cleanly; author/publisher inlined
    # because cross-page @id references don't resolve for crawlers.
    published_raw = str(story.get("published", ""))
    author_name = str(story.get("author") or "626 Labs")
    ld = {
        "@context": "https://schema.org",
        "@type": "BlogPosting",
        "headline": raw_title,
        "description": desc,
        "url": canonical,
        "mainEntityOfPage": {"@type": "WebPage", "@id": canonical},
        "datePublished": published_raw,
        "dateModified": str(story.get("updated") or published_raw),
        "image": og_image,
        "inLanguage": "en",
        "author": {
            "@type": "Organization" if author_name == "626 Labs" else "Person",
            "name": author_name,
            "url": f"{SITE_URL}/",
        },
        "publisher": {
            "@type": "Organization",
            "name": "626 Labs",
            "logo": {
                "@type": "ImageObject",
                "url": f"{SITE_URL}/assets/brand/icon-transparent-512.png",
            },
        },
    }
    ld_json = json.dumps(ld, ensure_ascii=False, indent=2)

    read_min = _reading_minutes(str(story.get("_body", "")))
    meta = [f'<span class="author">{author}</span>']
    if product:
        meta.append('<span class="sep">·</span>')
        meta.append(f"<span>{product}</span>")
    meta.append('<span class="sep">·</span>')
    meta.append(f'<span>{read_min} min read</span>')

    pager_cards = []
    if older:
        pager_cards.append(_ed_next_card(older, "Older Field Note", "older"))
    if newer:
        pager_cards.append(_ed_next_card(newer, "Newer Field Note", "newer"))
    pager = (
        '    <nav class="ed-pager" aria-label="More Field Notes">\n'
        + "\n".join(pager_cards) + "\n    </nav>\n"
    ) if pager_cards else ""

    head_block = "\n".join([
        f'<title>{title} — Field Notes — 626 Labs</title>',
        f'<meta name="description" content="{attr(desc)}" />',
        f'<link rel="canonical" href="{canonical}" />',
        f'<meta property="og:title" content="{attr(raw_title)}" />',
        f'<meta property="og:description" content="{attr(desc)}" />',
        '<meta property="og:type" content="article" />',
        f'<meta property="og:url" content="{canonical}" />',
        f'<meta property="og:image" content="{attr(og_image)}" />',
        '<meta name="twitter:card" content="summary_large_image" />',
        '<script type="application/ld+json">',
        ld_json,
        '</script>',
    ])

    h1_line = f'      <h1 class="ed-title">{title}</h1>'
    if subtitle:
        h1_line += f'\n      <p class="ed-dek">{esc(subtitle)}</p>'
    article_header_block = "\n".join([
        f'      <div class="ed-eyebrow">Field Note<span class="dot"></span><span class="num">{published}</span></div>',
        h1_line,
        f'      <div class="ed-meta">{"".join(meta)}</div>',
    ])

    out = shell
    for token, value in (
        ("READING:HEAD", head_block),
        ("READING:ARTICLE_HEADER", article_header_block),
        ("READING:BODY", body_html),
        ("READING:PAGER", pager),
    ):
        marker = "{{" + token + "}}"
        if marker not in out:
            raise RuntimeError(f"reading archetype missing token: {marker!r}")
        out = out.replace(marker, value, 1)
    return out


def render_story_pages(stories: list[dict], slug: str) -> list[tuple[Path, str]]:
    """(output_path, html) for each LOCAL published story, filled into `slug`'s
    `reading` archetype shell (themes/<slug>/archetypes/reading.html). Every
    Field Note page IS `reading` archetype by construction — there's no other
    archetype a generated editorial/<slug>/index.html page could be — so this
    resolves the shell path directly rather than round-tripping through
    archetypes.archetype_for() per page (that mapping is a drift *gate* for
    pages already on disk, via content/page-archetypes.json + validate(); it
    would be the wrong layer to also gate whether a brand-new local Field Note
    can render at all). Off-site (external_url) posts keep linking out and get
    no on-site page. Prev/next neighbors come from the newest-first local
    order (so the pager never points at a Medium post that has no on-site
    page); the returned list is sorted by path so the write order — and thus
    `--check` — is deterministic."""
    shell_path = theme_registry.theme_dir(slug) / "archetypes" / "reading.html"
    if not shell_path.exists():
        raise RuntimeError(
            f"reading archetype missing: {shell_path.relative_to(ROOT).as_posix()} "
            f"(theme {slug!r} has no reading dress yet)"
        )
    shell = shell_path.read_text(encoding="utf-8")

    local = [s for s in stories if not s.get("external_url")]  # newest-first
    pages: list[tuple[Path, str]] = []
    for i, s in enumerate(local):
        page_slug = story_slug(s)
        if not page_slug:
            continue
        newer = local[i - 1] if i > 0 else None
        older = local[i + 1] if i + 1 < len(local) else None
        body_html = _story_body_html(str(s.get("_body", "")))
        html_doc = render_story_page(s, body_html, shell, newer=newer, older=older)
        pages.append((STORY_PAGES_DIR / page_slug / "index.html", html_doc))
    pages.sort(key=lambda pc: pc[0].as_posix())
    return pages


def orphan_story_pages(stories: list[dict], root: Path = ROOT) -> list[Path]:
    """editorial/<slug>/ dirs that carry STORY_PAGE_MARKER but no longer map to
    a published local story — safe to prune (e.g. a note was unpublished or its
    slug changed). The marker check means hand-authored editorial pages, and the
    editorial/index.html landing page, are never candidates."""
    valid = {story_slug(s) for s in stories if not s.get("external_url")}
    ed = root / "editorial"
    if not ed.is_dir():
        return []
    orphans: list[Path] = []
    for d in sorted(p for p in ed.iterdir() if p.is_dir()):
        if d.name in valid:
            continue
        idx = d / "index.html"
        try:
            if idx.is_file() and STORY_PAGE_MARKER in idx.read_text(encoding="utf-8"):
                orphans.append(d)
        except OSError:
            continue
    return orphans


# ─── feed (Atom syndication for Field Notes) ────────────────────────
def _rfc3339(value: object) -> str:
    """Coerce a story's `published` (date-only ISO, e.g. 2026-04-23) into an
    RFC-3339 datetime for Atom. Pass through anything already carrying a time;
    fall back to FEED_EPOCH when empty."""
    s = str(value or "").strip()
    if not s:
        return FEED_EPOCH
    return s if "T" in s else f"{s}T00:00:00Z"


def render_atom_feed(stories: list[dict]) -> str:
    """Build the Field Notes Atom feed from the discovered stories.

    Deterministic by design: the feed's <updated> derives from the newest
    story's published date (never wall-clock), so `--check` stays idempotent
    and CI never sees phantom drift. Each <entry> links to its canonical home
    — external_url for off-site posts, the on-site /editorial/ page otherwise."""
    updated = _rfc3339(stories[0].get("published")) if stories else FEED_EPOCH
    entries = []
    for s in stories:
        link = story_link(s)
        when = _rfc3339(s.get("published"))
        summary = str(s.get("subtitle") or s.get("tagline") or "")
        author = str(s.get("author") or FEED_AUTHOR)
        entries.append(
            "  <entry>\n"
            f"    <title>{xesc(str(s.get('title', '')))}</title>\n"
            f'    <link href="{xesc(link)}"/>\n'
            f"    <id>{xesc(link)}</id>\n"
            f"    <updated>{when}</updated>\n"
            f"    <published>{when}</published>\n"
            f"    <author><name>{xesc(author)}</name></author>\n"
            f"    <summary>{xesc(summary)}</summary>\n"
            "  </entry>"
        )
    body = ("\n" + "\n".join(entries)) if entries else ""
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<feed xmlns="http://www.w3.org/2005/Atom">\n'
        f"  <title>{xesc(FEED_TITLE)}</title>\n"
        f"  <subtitle>{xesc(FEED_SUBTITLE)}</subtitle>\n"
        f'  <link href="{SITE_URL}/#field-notes"/>\n'
        f'  <link rel="self" type="application/atom+xml" href="{SITE_URL}/feed.xml"/>\n'
        f"  <id>{SITE_URL}/feed.xml</id>\n"
        f"  <updated>{updated}</updated>\n"
        f"  <author><name>{xesc(FEED_AUTHOR)}</name></author>"
        f"{body}\n"
        "</feed>\n"
    )


# ─── sitemap (XML sitemap for search crawlers) ──────────────────────
SITEMAP_PATH = ROOT / "sitemap.xml"
# Directories that have an index.html but should NOT be advertised to
# crawlers. "archive" is themes/archive/<YYYY-MM>/ — frozen, noindex'd theme
# snapshots (see scripts/freeze-theme.py); they carry their own <meta
# name="robots" content="noindex"> so a crawler that finds one anyway won't
# rank it, but they have no business being *advertised* via the sitemap
# either. Add a dir name here to keep a future preview/private surface out.
SITEMAP_EXCLUDE: frozenset[str] = frozenset({"archive"})
# Root-level *.html files that should NOT appear in the sitemap. index.html
# maps to "/" on its own; 404.html is an error page; admin-dashboard.html is
# the PAT-gated admin surface and must stay out of crawler view. Every other
# top-level page (rororo, thesis, workflow, privacy, ...) is public content.
SITEMAP_ROOT_HTML_EXCLUDE: frozenset[str] = frozenset(
    {"index.html", "404.html", "admin-dashboard.html"}
)


def render_sitemap(stories: list[dict] | None = None, root: Path = ROOT) -> str:
    """Build an XML sitemap from the pages actually on disk plus the Field Notes.

    Enumerates four page classes, all derived from real content so the sitemap
    never drifts from what ships:
      1. the root index.html              -> "/"                  (daily, 1.0)
      2. every <dir>/index.html one down  -> "/<dir>/"            (weekly, 0.8)
      3. standalone root <name>.html      -> "/<name>.html"       (monthly, 0.6)
      4. each local Field Note            -> "/editorial/<slug>/" (monthly, 0.7)
    Class 3 covers the hand-authored content pages (rororo, thesis, workflow,
    privacy) the dir walk would otherwise miss; SITEMAP_ROOT_HTML_EXCLUDE keeps
    index/404/admin out. Class 4 carries a <lastmod> from each note's frontmatter
    date (deterministic — no git needed). Add a page or publish a note and it
    appears here automatically. Deterministic ordering (home, dirs, root pages,
    notes — each alphabetical) keeps --check idempotent.
    """
    if stories is None:
        stories = discover_stories()
    # (loc, changefreq, priority, lastmod | None)
    pages: list[tuple[str, str, str, str | None]] = []
    if (root / "index.html").exists():
        pages.append((f"{SITE_URL}/", "daily", "1.0", None))
    for idx in sorted(root.glob("*/index.html"), key=lambda p: p.parent.name):
        name = idx.parent.name
        if name in SITEMAP_EXCLUDE:
            continue
        pages.append((f"{SITE_URL}/{name}/", "weekly", "0.8", None))
    for html_file in sorted(root.glob("*.html"), key=lambda p: p.name):
        if html_file.name in SITEMAP_ROOT_HTML_EXCLUDE:
            continue
        pages.append((f"{SITE_URL}/{html_file.name}", "monthly", "0.6", None))
    for s in sorted((s for s in stories if not s.get("external_url")), key=story_slug):
        slug = story_slug(s)
        if not slug:
            continue
        lastmod = str(s.get("updated") or s.get("published") or "")[:10] or None
        pages.append((f"{SITE_URL}/editorial/{slug}/", "monthly", "0.7", lastmod))

    blocks = []
    for loc, cf, pr, lastmod in pages:
        block = ["  <url>", f"    <loc>{xesc(loc)}</loc>"]
        if lastmod:
            block.append(f"    <lastmod>{xesc(lastmod)}</lastmod>")
        block.append(f"    <changefreq>{cf}</changefreq>")
        block.append(f"    <priority>{pr}</priority>")
        block.append("  </url>")
        blocks.append("\n".join(block))
    urls = "\n".join(blocks)
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        f"{urls}\n"
        "</urlset>\n"
    )


# ─── section toggles ────────────────────────────────────────────────
# Maps sections keys in site.json → DOM id of the <section> element.
# NOTE: re-enabling "thinking" needs BOTH the `thinking` content key back in
# site.json AND sections.thinking.enabled: true — flipping the toggle alone
# can't revive it, since main() only renders the zone when the key is present
# (see the `"thinking" in content` guard below), leaving no <section id=
# "thinking"> element for this toggle to find.
SECTION_IDS = {
    "thinking": "thinking",
    "founding": "founding",
    "labRuns":  "lab-runs",
    "lab":      "lab",
    "play":     "play",
    "about":    "about",
    "support":  "support",
    "contact":  "contact",
}


def toggle_section(html: str, section_id: str, enabled: bool) -> str:
    """Add or strip the HTML `hidden` attribute on the section with this id.

    Native `<section hidden>` gets display:none in every browser. Preserves
    the section's content so toggling back on restores it instantly — no
    regeneration needed.
    """
    pattern = re.compile(
        r"(<section\s[^>]*id=\"" + re.escape(section_id) + r"\"[^>]*>)",
        re.IGNORECASE,
    )

    def replace(m: re.Match) -> str:
        tag = m.group(1)
        # Strip any existing `hidden` attribute (idempotent).
        tag = re.sub(r'\s+hidden(?=[\s>])', "", tag)
        if not enabled:
            tag = tag[:-1] + " hidden>"
        return tag

    return pattern.sub(replace, html, count=1)


def apply_section_toggles(html: str, sections: dict) -> str:
    for key, dom_id in SECTION_IDS.items():
        enabled = bool((sections.get(key) or {}).get("enabled", True))
        html = toggle_section(html, dom_id, enabled)
    return html


# ─── main ───────────────────────────────────────────────────────────
def main(argv: list[str]) -> int:
    # --list-renderer-owned-pages: one repo-relative, posix-style path per
    # line, and nothing else on stdout. Every hand-authored page this script
    # rewrites on a run — the theme-css pages plus about.html's easter-egg
    # registry — so the CI workflows stop hand-enumerating them.
    #
    # Same mechanism, and the same reason, as
    # render-plugin-pages.py --list-outputs. Those nine names were repeated
    # in three places across two workflows with nothing comparing them to
    # THEME_CSS_HREFS. Add a tenth page to that map, and: the renderer
    # rewrites it, --check passes because it WAS rendered, the commit step's
    # list does not name it, and main() ships nine pages wearing the new
    # theme and one wearing the old. This repo has already had that exact
    # bug once — A8 found press.html/privacy.html/about.html missing from
    # rotate-theme.yml's git-add list, after a rotation had run.
    #
    # index.html/feed.xml/sitemap.xml/editorial/ are deliberately NOT here:
    # they are pipeline outputs the workflows name for their own reasons,
    # not the hand-authored-page seam this exists to keep honest.
    if "--list-renderer-owned-pages" in argv:
        # LF explicitly — on Windows print() emits CRLF and a trailing \r
        # reaches git as a different pathspec. Same discipline
        # render-plugin-pages.py --list-outputs documents.
        pages = sorted(
            {*THEME_CSS_HREFS, ABOUT_HTML},
            key=lambda p: p.relative_to(ROOT).as_posix(),
        )
        sys.stdout.reconfigure(newline="\n")
        sys.stdout.write(
            "".join(f"{p.relative_to(ROOT).as_posix()}\n" for p in pages)
        )
        return 0

    theme_slug = None
    if "--theme" in argv:
        theme_slug = argv[argv.index("--theme") + 1]
    out_dir = None
    if "--out" in argv:
        out_dir = Path(argv[argv.index("--out") + 1])

    # --theme without --out would render an arbitrary theme straight over the
    # LIVE index.html and every other site surface (feed, sitemap, story
    # pages, themes.html) — preview mode requires both flags together, always.
    if theme_slug and not out_dir:
        print(
            "error: --theme requires --out — a bare --theme would render that "
            "theme over the live index.html and every other site surface. "
            "Use: render-hub.py --theme <slug> --out <dir>",
            file=sys.stderr,
        )
        return 2

    reg = theme_registry.load()
    slug = theme_slug or theme_registry.active_slug(reg)
    # index.html is the "home" archetype (content/page-archetypes.json). A
    # theme dresses it from themes/<slug>/archetypes/home.html — every theme
    # is required to carry all four archetype files (home, product, reading,
    # utility; see theme_registry.REQUIRED_ARCHETYPES). The legacy single
    # shell.html fallback that covered A2-A3 of the archetype rollout is
    # gone as of A4: a missing archetype file is a loud error, not a silent
    # render-around.
    page_archetype = archetypes.archetype_for("index.html", archetypes.load())
    shell = theme_registry.theme_dir(slug) / "archetypes" / f"{page_archetype}.html"
    if not shell.exists():
        # A missing shell used to fall back to reading the live index.html as
        # source, which makes `--check` trivially green forever (comparing
        # the live file against itself) and silently renders nothing when a
        # theme is incomplete. Fail loudly instead — an incomplete theme is
        # a bug to fix, not a state to render around.
        print(
            f"error: theme archetype missing: {shell.relative_to(ROOT).as_posix()} "
            f"(theme '{slug}' is incomplete — expected archetypes/{page_archetype}.html, "
            "plus tokens.css and theme.json, under themes/<slug>/)",
            file=sys.stderr,
        )
        return 2
    src = shell.read_text(encoding="utf-8")
    dest = (out_dir / "index.html") if out_dir else INDEX_HTML

    content = json.loads(SITE_JSON.read_text(encoding="utf-8"))
    content = site_facts.resolve_tokens(content, site_facts.facts())

    stories = discover_stories()

    out = src
    out = substitute_zone(out, "hero", render_hero(content["hero"]))
    out = substitute_zone(out, "hero-chips", render_chips(content["hero"]["chips"]))
    out = substitute_zone(out, "products",
                          render_products(content["products"], content.get("pluginFamily")))
    out = substitute_zone(out, "lab-pool", render_lab_pool(content["lab"]), js=True)
    out = substitute_zone(
        out, "thinking",
        render_thinking(content["thinking"]) if "thinking" in content else "")
    out = substitute_zone(
        out, "founding",
        render_founding(content["founding"]) if "founding" in content else "")
    out = substitute_zone(out, "stories", render_field_notes(stories))
    if "labRuns" in content:
        out = substitute_zone(out, "lab-runs", render_lab_runs(content["labRuns"]))
    if "play" in content:
        out = substitute_zone(out, "play", render_play_section(content["play"]))
    if "about" in content:
        out = substitute_zone(
            out, "about",
            render_about(content["about"], content.get("products") or []),
        )
    if "support" in content:
        out = substitute_zone(out, "support", render_support(content["support"]))
    if "contact" in content:
        out = substitute_zone(out, "contact", render_contact(content["contact"]))
    out = apply_section_toggles(out, content.get("sections") or {})

    # Preview mode (--theme/--out): render the home page plus every
    # theme-css page, into out_dir and nowhere else — no feed, no sitemap,
    # no editorial/ story pages, no orphan pruning, and nothing written back
    # into the repo tree.
    #
    # The theme-css pages are here because a queued theme's effect on them
    # was otherwise un-previewable and un-gateable: index.html is rendered
    # from the theme's own shell, but press.html/privacy.html/thesis.html/
    # workflow.html/conundrum.html/rororo-plugins.html/rororo.html/
    # mod-launcher-games.html are hand-authored pages whose only
    # theme-derived seam is that one <link>. Without this,
    # the ONLY way to see a queued theme's reading or product dress on a
    # real page of that archetype was to make it active and look at
    # production. Each is copied with its zone repointed at `slug`, never at
    # whatever content/themes.json currently says.
    #
    # The copies keep root-relative asset paths (/themes/..., /fonts/...,
    # /assets/...), so serve them from the REPO ROOT with out_dir's copies
    # laid over the top — the same shape theme-doctor's own preview server
    # uses for index.html. Opening one straight off disk resolves nothing.
    if out_dir is not None:
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(out, encoding="utf-8")
        print(f"preview written: {dest}")
        for page_path in PREVIEWABLE_THEME_CSS_PAGES:
            preview = substitute_zone(
                page_path.read_text(encoding="utf-8"),
                "theme-css",
                render_theme_css_link(slug, THEME_CSS_HREFS[page_path]),
            )
            page_dest = out_dir / page_path.name
            page_dest.write_text(preview, encoding="utf-8")
            print(f"preview written: {page_dest}")
        return 0

    # conundrum.html — shop page zones (gallery + repo CTA) PLUS its
    # "theme-css" link (see THEME_CSS_HREFS / THEME_CSS_MULTI_ZONE_PAGES
    # above). Rendered here rather than in the theme-css loop below
    # precisely because it has other zones: two blocks each reading the
    # page off disk and writing it back would have the later write revert
    # the earlier one. The theme-css substitution is unconditional — the
    # gallery zones depend on the "conundrum" key existing, the stylesheet
    # link does not.
    conundrum_old = CONUNDRUM_HTML.read_text(encoding="utf-8")
    conundrum_new = substitute_zone(
        conundrum_old, "theme-css",
        render_theme_css_link(slug, THEME_CSS_HREFS[CONUNDRUM_HTML]),
    )
    if "conundrum" in content:
        conundrum_new = substitute_zone(
            conundrum_new, "conundrum-products",
            render_conundrum_products(content["conundrum"]),
        )
        conundrum_new = substitute_zone(
            conundrum_new, "conundrum-repo",
            render_conundrum_repo(content["conundrum"]),
        )
    conundrum_changed = conundrum_new != conundrum_old

    # themes.html — the rotation gallery, plus its "theme-css" stylesheet
    # link (see THEME_CSS_HREFS above). Always rendered — content/
    # themes.json always has an active theme, so there's always >=1 card
    # and always a slug to point the stylesheet at.
    themes_old = THEMES_HTML.read_text(encoding="utf-8")
    themes_new = substitute_zone(themes_old, "themes", render_themes_gallery(reg))
    themes_new = substitute_zone(
        themes_new, "theme-css", render_theme_css_link(slug, THEME_CSS_HREFS[THEMES_HTML])
    )
    themes_changed = themes_new != themes_old

    # press.html / privacy.html / thesis.html / workflow.html /
    # rororo-plugins.html / rororo.html / mod-launcher-games.html — no
    # other zones, just the "theme-css" link (see THEME_CSS_HREFS above).
    # conundrum.html has the same link but is rendered in its own block
    # above, beside its gallery zones.
    theme_css_pages = []
    for page_path in THEME_CSS_ONLY_PAGES:
        page_old = page_path.read_text(encoding="utf-8")
        page_new = substitute_zone(
            page_old, "theme-css", render_theme_css_link(slug, THEME_CSS_HREFS[page_path])
        )
        theme_css_pages.append((page_path, page_new, page_new != page_old))

    # about.html — one renderer-owned zone, the easter-egg theme registry
    # (see render_about_theme_dresses above). Everything else on this page
    # stays hand-authored; this is the same narrow-seam trade
    # THEME_CSS_HREFS already made for press.html/privacy.html/themes.html.
    about_old = ABOUT_HTML.read_text(encoding="utf-8")
    about_new = substitute_zone(about_old, "about-theme-toggle", render_about_theme_dresses(reg))
    about_changed = about_new != about_old

    feed_new = render_atom_feed(stories)
    feed_old = FEED_PATH.read_text(encoding="utf-8") if FEED_PATH.exists() else None

    sitemap_new = render_sitemap(stories)
    sitemap_old = SITEMAP_PATH.read_text(encoding="utf-8") if SITEMAP_PATH.exists() else None

    # On-site Field Note pages — (path, new_html, changed) per local story.
    story_pages = []
    for path, new_html in render_story_pages(stories, slug):
        old = path.read_text(encoding="utf-8") if path.exists() else None
        story_pages.append((path, new_html, new_html != old))
    orphans = orphan_story_pages(stories)

    # Compare against what's actually on disk at dest, not against src (the
    # shell we read from). src is a theme template; dest is the real
    # artifact. Comparing against src would make this trivially "unchanged"
    # forever once dest and the shell diverge — dest is the only truthful
    # baseline for drift detection.
    dest_before = dest.read_text(encoding="utf-8") if dest.exists() else None
    index_changed = out != dest_before
    feed_changed = feed_new != feed_old
    sitemap_changed = sitemap_new != sitemap_old
    stale_stories = [p for p, _, changed in story_pages if changed]

    if "--check" in argv:
        stale = [name for name, drifted in
                 (("index.html", index_changed), ("feed.xml", feed_changed),
                  ("sitemap.xml", sitemap_changed),
                  ("conundrum.html", conundrum_changed),
                  ("themes.html", themes_changed),
                  ("about.html", about_changed)) if drifted]
        stale += [
            page_path.relative_to(ROOT).as_posix()
            for page_path, _, changed in theme_css_pages if changed
        ]
        stale += [p.relative_to(ROOT).as_posix() for p in stale_stories]
        stale += [f"{d.relative_to(ROOT).as_posix()}/ (orphaned — prune)" for d in orphans]
        if stale:
            print(
                f"{' and '.join(stale)} out of date relative to content. "
                "Run scripts/render-hub.py.",
                file=sys.stderr,
            )
            return 1
        print(
            f"index.html, feed.xml, sitemap.xml and {len(story_pages)} "
            "Field Note page(s) are up to date."
        )
        return 0

    if index_changed:
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(out, encoding="utf-8")
        print(f"index.html rebuilt from {SITE_JSON.relative_to(ROOT)}")
    else:
        print("index.html already matches content/site.json — no change.")

    if conundrum_changed:
        CONUNDRUM_HTML.write_text(conundrum_new, encoding="utf-8")
        # Both sources, because both zones live on this page — and on a
        # rotation the themes.json half is the ONLY reason it changes.
        print("conundrum.html zones rebuilt from content/site.json + content/themes.json")

    if themes_changed:
        THEMES_HTML.write_text(themes_new, encoding="utf-8")
        print("themes.html zone rebuilt from content/themes.json")

    for page_path, page_new, page_changed in theme_css_pages:
        if page_changed:
            page_path.write_text(page_new, encoding="utf-8")
            print(f"{page_path.relative_to(ROOT)} theme-css zone rebuilt for active theme {slug!r}")

    if about_changed:
        ABOUT_HTML.write_text(about_new, encoding="utf-8")
        print("about.html theme-toggle registry rebuilt from content/themes.json")

    if feed_changed:
        FEED_PATH.write_text(feed_new, encoding="utf-8")
        print(f"feed.xml rebuilt from {STORIES_DIR.relative_to(ROOT)}/")
    else:
        print("feed.xml already current — no change.")

    if sitemap_changed:
        SITEMAP_PATH.write_text(sitemap_new, encoding="utf-8")
        print("sitemap.xml rebuilt from the page tree.")
    else:
        print("sitemap.xml already current — no change.")

    rebuilt = 0
    for path, new_html, changed in story_pages:
        if changed:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(new_html, encoding="utf-8")
            print(f"Field Note page rebuilt: {path.relative_to(ROOT).as_posix()}")
            rebuilt += 1
    if not rebuilt:
        print(f"{len(story_pages)} Field Note page(s) already current — no change.")

    for d in orphans:
        shutil.rmtree(d)
        print(f"Field Note page pruned (orphaned): {d.relative_to(ROOT).as_posix()}/")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))

THEME_STATUS_LABEL = {"live": "Live", "queued": "Queued", "archived": "Archived"}


def _theme_month_label(month: str | None) -> str:
    """'2026-08' -> 'August 2026'. Falls back to the raw string for anything
    that doesn't parse as YYYY-MM (never crashes the render on a malformed
    value), and to "" when there's no month at all."""
    if not month:
        return ""
    try:
        return datetime.strptime(month, "%Y-%m").strftime("%B %Y")
    except ValueError:
        return month


def _theme_meta(slug: str, root: Path) -> dict:
    """Best-effort name/thesis/month straight off the theme's own
    theme.json. A card's STATUS and LINK come from the registry only (see
    render_themes_gallery) — never from here — so the gallery can't
    disagree with content/themes.json even if a theme.json goes stale.
    Falls back to a slug-derived name when the file is missing or
    unreadable (an archived theme's source dir isn't guaranteed to stick
    around forever)."""
    meta_path = theme_registry.theme_dir(slug, root) / "theme.json"
    name = slug.replace("-", " ").title()
    thesis = ""
    month = None
    if meta_path.exists():
        try:
            data = json.loads(meta_path.read_text(encoding="utf-8"))
            name = data.get("name") or name
            thesis = data.get("thesis") or ""
            month = data.get("month")
        except (json.JSONDecodeError, OSError):
            pass
    return {"name": name, "thesis": thesis, "month": month}


def _theme_thumbnail_href(slug: str, root: Path) -> str | None:
    """Root-relative /assets/themes/<slug>.png href, or None when no capture
    exists yet. scripts/freeze-theme.py's capture_theme_screenshot() is the
    only writer of this path — the freeze step captures a retiring theme,
    the promote step captures the incoming one (see rotate-theme.yml and
    docs/theme-archetypes.md). A theme that hasn't been through a live
    rotation yet (freshly queued, or the very first active theme before its
    first capture) simply has no file here, and the card renders without a
    thumbnail — never a broken <img>, never a placeholder."""
    path = root / "assets" / "themes" / f"{slug}.png"
    return f"/assets/themes/{slug}.png" if path.exists() else None


def _render_theme_card(slug: str, status: str, month: str | None, link: str | None, root: Path) -> str:
    meta = _theme_meta(slug, root)
    thumb_href = _theme_thumbnail_href(slug, root)
    head_bits = [f'<span class="theme-status {status}">{THEME_STATUS_LABEL[status]}</span>']
    month_label = _theme_month_label(month)
    if month_label:
        head_bits.append(f'<span class="theme-month">{esc(month_label)}</span>')

    lines = []
    if thumb_href:
        lines.append(
            f'  <img class="theme-thumb" src="{attr(thumb_href)}" '
            f'alt="{esc(meta["name"])} thumbnail" loading="lazy" width="1440" height="900">'
        )
    lines += [
        '  <div class="theme-card-head">',
        "    " + "\n    ".join(head_bits),
        "  </div>",
        f'  <h3 class="theme-name">{esc(meta["name"])}</h3>',
    ]
    if meta["thesis"]:
        lines.append(f'  <p class="theme-thesis">{esc(meta["thesis"])}</p>')
    inner = "\n".join(lines)

    tag = "a" if link else "div"
    href_attr = f' href="{attr(link)}"' if link else ""
    return f'<{tag} class="theme-card {status}"{href_attr}>\n{inner}\n</{tag}>'


def render_themes_gallery(reg: dict, root: Path = ROOT) -> str:
    """One card per theme in content/themes.json — active first (links "/"),
    then the queue in rotation order (no link, a "queued" chip), then the
    archive newest-first (links its registry `url`). Renders straight from
    the registry so a card's status/link can never disagree with what's
    actually live; only name/thesis/month get enriched from each theme's
    own theme.json (see _theme_meta). Archived months come from the
    registry entry itself — the authoritative record of when that theme
    was actually live — not the theme.json's original (possibly
    aspirational) month. An active theme is guaranteed by
    theme_registry.validate(), so this never renders zero cards."""
    cards = []
    active = reg.get("active")
    if active:
        meta = _theme_meta(active, root)
        cards.append(_render_theme_card(active, "live", meta["month"], "/", root))
    for slug in reg.get("queue") or []:
        meta = _theme_meta(slug, root)
        cards.append(_render_theme_card(slug, "queued", meta["month"], None, root))
    for entry in reversed(reg.get("archive") or []):
        cards.append(_render_theme_card(
            entry.get("slug", ""), "archived", entry.get("month"), entry.get("url"), root
        ))
    return "\n\n".join(cards)


# ─── hand-authored pages' theme stylesheet ("theme-css" zone) ──────────────
#
# These pages carry no site.json-driven content — unlike index.html's
# SITE_JSON zones or the Field Notes' markdown, nothing regenerates them
# from data. But their <head> stylesheet <link> was hardcoded to
# "phosphor-blueprint" specifically, which meant they'd stay frozen in
# that dress forever even after the site rotates to a different theme
# (found in A4 review — utility.html had zero live consumers, so "the
# whole site rotates" had a real gap). This zone is the fix: the link
# stays renderer-owned, computed from the ACTIVE theme every run, same
# governance as the "themes" zone above even though no page content
# changes.
#
# NAME: this was UTILITY_CSS_HREFS when press/privacy/themes were its
# only members. It now carries reading AND product pages, so it is named
# for what it does — map a hand-authored page to the theme-relative
# stylesheet its "theme-css" zone should point at — rather than for the
# one archetype it started with.
#
# press.html/privacy.html link archetypes/utility.css (their shared chrome,
# extracted verbatim from press.html — see themes/phosphor-blueprint/
# archetypes/utility.css's header comment). thesis.html/workflow.html link
# archetypes/reading-tokens.css, which is where their base token
# vocabulary and the Phosphor Blueprint treatment tokens now live (each
# page used to carry a private copy of both, which no rotation could
# reach). Deliberately NOT archetypes/reading.css: that file is the Long
# Now Terminal DRESS about.html's theme picker wears, and a dress a page
# links for its palette alone is free to grow an element rule that lands
# on it uninvited — which is exactly what happened on the product
# archetype before it was split. themes.html keeps tokens.css:
# switching it to utility.css would have changed its pixels (utility.css's
# unconditional `h1 { text-shadow }` doesn't apply to themes.html today —
# tokens.css's `header.hero h1` never matched `.page-hero` either, so
# themes.html's h1 currently has no bloom at all; and press.html's
# `.page-lead` is `max-width: 60ch` where themes.html's own copy is
# `62ch`). All four bespoke product pages — conundrum.html,
# rororo-plugins.html, rororo.html, mod-launcher-games.html — link
# archetypes/product-tokens.css, the TOKEN half of the product
# archetype, where THEIR private :root copies went. Deliberately not
# archetypes/product.css: that file is the element dress
# render-plugin-pages.py inlines into its 15 generated pages, written on
# bare element selectors (`body`, `a:hover`, `section.hero`, `.card`,
